
import streamlit as st
import pandas as pd
import joblib

# Step 1: Configure the page
st.set_page_config(
    page_title="Multi-Emotion Text Detector",
    page_icon="😊",
    layout="wide"
)

# Step 2: Page heading
st.title("😊 Multi-Emotion Text Detector")
st.write(
    "Enter a sentence to predict its most likely emotion "
    "using a machine learning model."
)

# Step 3: Load the trained model
@st.cache_resource
def load_model():
    return joblib.load("best_emotion_model.joblib")

try:
    model = load_model()
except Exception as e:
    st.error(f"Could not load the emotion model: {e}")
    st.stop()

# Step 4: Enter text
st.subheader("Enter Your Text")

user_text = st.text_area(
    "Type a sentence:",
    placeholder="Example: I am so happy that I passed my exam!",
    height=120
)

# Step 5: Predict emotion

# Step 5: Predict emotion
if st.button("Detect Emotion", type="primary"):
    if not user_text.strip():
        st.warning("Please enter a sentence first.")
    else:
        try:
            prediction = model.predict([user_text])[0]

            st.subheader("Predicted Emotion")
            st.success(str(prediction).title())

            st.caption(
                "This prediction is generated by a machine learning model "
                "and may not always reflect the sentence's actual meaning."
            )

        except Exception as e:
            st.error(f"Prediction failed: {e}")


            # Step 6: Calculate emotion scores
            if hasattr(model, "predict_proba"):
                probabilities = model.predict_proba([user_text])[0]

                # Get the correct emotion labels from the model
                classifier = model.named_steps.get("classifier")
                emotions = classifier.classes_

                scores = pd.DataFrame({
                    "Emotion": emotions,
                    "Score": probabilities
                })

                # Sort scores from highest to lowest
                scores = scores.sort_values(
                    by="Score",
                    ascending=False
                ).reset_index(drop=True)

                # Display the top five emotions
                st.subheader("Top 5 Emotion Scores")

                top5 = scores.head(5).copy()
                top5["Score (%)"] = (top5["Score"] * 100).round(2)

                st.bar_chart(
                    top5.set_index("Emotion")["Score (%)"]
                )

                st.dataframe(
                    top5[["Emotion", "Score (%)"]],
                    hide_index=True,
                    use_container_width=True
                )

                st.caption(
                    "Scores are model-estimated probabilities, "
                    "not measurements of actual emotional intensity."
                )

                # Optional: show all emotion scores
                with st.expander("View all emotion scores"):
                    all_scores = scores.copy()
                    all_scores["Score (%)"] = (
                        all_scores["Score"] * 100
                    ).round(2)

                    st.dataframe(
                        all_scores[["Emotion", "Score (%)"]],
                        hide_index=True,
                        use_container_width=True
                    )

            else:
                st.info(
                    "This model does not provide probability scores."
                )

        except Exception as e:
            st.error(f"Prediction failed: {e}")

# Step 7: About section
st.divider()
with st.expander("About this project"):
    st.write("""
    **Project:** Multi-Emotion Text Detector

    **Machine learning:** TF-IDF and Logistic Regression

    **Dataset:** Labeled tweets containing 12 emotion categories.

    **Model comparison:** Logistic Regression, Multinomial Naive Bayes,
    and Linear SVM.

    **Best model selection:** Logistic Regression based on macro F1 score.

    **Test accuracy:** Approximately 29.07%.

    This is an educational text-classification project. Predictions may
    be incorrect, particularly for underrepresented emotions.
    """)
